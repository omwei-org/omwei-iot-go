// Command omwei-gen generates the compiled-in descriptor table from the YAML
// corpus. It is the Go counterpart of the Rust crate's build.rs.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"

	"github.com/omwei-org/omwei-iot-go/corpus"
)

func main() {
	in := flag.String("in", "registry/corpus-v0.1.yaml", "corpus YAML")
	out := flag.String("out", "registry_generated.go", "generated Go file")
	pkg := flag.String("pkg", "omwei", "package name")
	flag.Parse()

	src, err := os.ReadFile(*in)
	if err != nil {
		log.Fatal(err)
	}
	c, err := corpus.Parse(string(src))
	if err != nil {
		log.Fatalf("registry corpus validation failed: %v", err)
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by omwei-gen from %s; DO NOT EDIT.\n\npackage %s\n\n", *in, *pkg)
	fmt.Fprintf(&b, "const (\n\tRegistryID    = %q\n\tSchemaVersion = %q\n\tCorpusVersion = %q\n)\n\n",
		c.Metadata.RegistryID, c.Metadata.SchemaVersion, c.Metadata.CorpusVersion)
	b.WriteString("var descriptors = [...]Descriptor{\n")
	for _, d := range c.Descriptors {
		fmt.Fprintf(&b, "\t{ID: 0x%04X, Label: %q, Unit: %q, QuantityKind: %q, Mappings: []SemanticMapping{",
			d.ID, d.Label, d.Unit, d.QuantityKind)
		for i, m := range d.Mappings {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "{Vocabulary: %q, Concept: %q}", m.Vocabulary, m.Concept)
		}
		fmt.Fprintf(&b, "}, Scale: %d, Offset: %d, Min: %d, Max: %d},\n",
			d.Scale, d.Offset, d.Min, d.Max)
	}
	b.WriteString("}\n")
	formatted, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, formatted, 0o644); err != nil {
		log.Fatal(err)
	}
}
